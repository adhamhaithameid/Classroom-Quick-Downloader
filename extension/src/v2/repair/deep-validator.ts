/**
 * ============================================================================
 * DEEP VALIDATOR — Idle-Time DOM Integrity Checker
 * ============================================================================
 *
 * The fast pass (fullScan in engine-v2.ts) runs on every mutation batch
 * and must be <6ms p95. That means it can miss things:
 * - Buttons removed by Google's DOM updates
 * - Badges showing wrong verdict after post content changed
 * - Orphaned elements from posts that were removed
 * - Duplicate injections from race conditions
 *
 * The deep validator catches ALL of these. It runs in idle callbacks
 * (requestIdleCallback) so it NEVER blocks the main thread. Each
 * validation slice is capped at IdleDeadline.timeRemaining() to
 * ensure smooth scrolling.
 *
 * Architecture:
 *   Engine fullScan() completes
 *     → schedules deepValidate()
 *     → validator checks each post against its PostNode model
 *     → divergences → CorrectionItem → correction-queue.ts
 *     → queue processes fixes in idle slices
 *
 * Backoff: if the same element is corrected 3+ times in 10s,
 * it's marked as "unstable" and skipped. This prevents infinite
 * repair loops when Google keeps overwriting our injections.
 *
 * @author Adham — this catches the edge cases that drove me crazy in V1
 * @since v4.0.0
 */

import type {
  PostNode,
  FlagDecision,
  PlacementDecision,
} from '../../engines/types';

// ============================================================================
// TYPES
// ============================================================================

/**
 * Priority levels for corrections.
 * CRITICAL: visible element missing/broken — user can see the problem
 * HIGH: visible element with wrong data
 * MEDIUM: preload-zone element (about to scroll into view)
 * LOW: offscreen element
 */
export type CorrectionPriority = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW';

/**
 * Types of corrections the validator can request.
 */
export type CorrectionOp =
  | 'inject-button'
  | 'remove-button'
  | 'update-flag'
  | 'remove-flag'
  | 'fix-overlay'
  | 'full-rescan';

/**
 * A single correction item generated by the deep validator.
 */
export interface CorrectionItem {
  /** Unique ID for dedup */
  id: string;
  /** What to fix */
  op: CorrectionOp;
  /** Priority based on visibility */
  priority: CorrectionPriority;
  /** Post ID this correction applies to */
  postId: string;
  /** Optional file ID (for button corrections) */
  fileId?: string;
  /** The DOM element to operate on */
  element: HTMLElement;
  /** Why this correction is needed */
  reason: string;
  /** Timestamp when detected */
  detectedAt: number;
  /** How many times we've tried to fix this */
  retryCount: number;
}

/**
 * Viewport zone hint (from viewport-observer.ts).
 * Used to determine correction priority.
 */
export type ViewportZone = 'visible' | 'preload' | 'offscreen';

/**
 * Result of a single validation pass.
 */
export interface ValidationResult {
  /** Total posts checked */
  postsChecked: number;
  /** Number of divergences found */
  divergencesFound: number;
  /** Corrections generated */
  corrections: CorrectionItem[];
  /** Posts skipped due to instability */
  unstableSkipped: number;
  /** Time taken for this pass (ms) */
  duration_ms: number;
  /** Whether the pass was interrupted by deadline */
  interrupted: boolean;
}

// ============================================================================
// CONSTANTS
// ============================================================================

/** If an element is corrected this many times in UNSTABLE_WINDOW_MS, skip it */
const MAX_RETRIES = 3;

/** Time window for retry counting (ms) */
const UNSTABLE_WINDOW_MS = 10_000;

/** Maximum posts to check per idle slice */
const MAX_POSTS_PER_SLICE = 50;

/** Minimum timeRemaining to start checking another post (ms) */
const MIN_TIME_REMAINING_MS = 2;

// ============================================================================
// INSTABILITY TRACKER
// ============================================================================

/**
 * Tracks which elements have been corrected recently.
 * Key: element ID (postId or postId:fileId), Value: correction timestamps.
 */
const correctionHistory = new Map<string, number[]>();

/**
 * Elements marked as unstable (too many corrections in short time).
 */
const unstableElements = new Set<string>();

/**
 * Record a correction attempt for an element.
 * Returns true if the element is now unstable (should be skipped).
 */
export function recordCorrection(elementId: string): boolean {
  const now = Date.now();

  // Get or create history
  let history = correctionHistory.get(elementId);
  if (!history) {
    history = [];
    correctionHistory.set(elementId, history);
  }

  // Add timestamp
  history.push(now);

  // Prune old entries outside the window
  const cutoff = now - UNSTABLE_WINDOW_MS;
  const recent = history.filter(t => t > cutoff);
  correctionHistory.set(elementId, recent);

  // Check if unstable
  if (recent.length >= MAX_RETRIES) {
    unstableElements.add(elementId);
    return true;
  }

  return false;
}

/**
 * Check if an element is marked as unstable (should be skipped).
 */
export function isUnstable(elementId: string): boolean {
  return unstableElements.has(elementId);
}

/**
 * Clear all instability tracking state.
 * Called on engine destroy or route transition.
 */
export function clearInstabilityState(): void {
  correctionHistory.clear();
  unstableElements.clear();
}

/**
 * Get count of unstable elements (for telemetry).
 */
export function getUnstableCount(): number {
  return unstableElements.size;
}

// ============================================================================
// VALIDATION CHECKS
// ============================================================================

/**
 * Check a single post for divergences between model and DOM.
 *
 * Returns an array of CorrectionItems (empty if post is healthy).
 */
export function validatePost(
  post: PostNode,
  flagDecision: FlagDecision | null,
  placements: PlacementDecision[],
  getViewportZone?: (el: HTMLElement) => ViewportZone,
): CorrectionItem[] {
  const corrections: CorrectionItem[] = [];
  const postEl = post.element;

  // Skip if element is no longer connected to the DOM
  if (!postEl.isConnected) return corrections;

  // Skip if element is unstable
  if (isUnstable(post.id)) return corrections;

  const zone = getViewportZone?.(postEl) ?? 'offscreen';
  const basePriority = zoneToPriority(zone);

  // CHECK 1: Missing buttons — model says files exist but no CQD buttons
  for (const file of post.files) {
    const hasButton = postEl.querySelector(
      `[data-cqd-injected][data-cqd-file-id="${file.canonicalId}"]`,
    );
    if (!hasButton) {
      corrections.push({
        id: `inject-btn:${post.id}:${file.canonicalId}`,
        op: 'inject-button',
        priority: basePriority,
        postId: post.id,
        fileId: file.canonicalId,
        element: postEl,
        reason: `Missing button for file ${file.canonicalId}`,
        detectedAt: Date.now(),
        retryCount: 0,
      });
    }
  }

  // CHECK 2: Orphaned buttons — CQD buttons exist but no matching file in model
  const injectedButtons = postEl.querySelectorAll<HTMLElement>('[data-cqd-injected][data-cqd-file-id]');
  const modelFileIds = new Set(post.files.map(f => f.canonicalId));
  for (const btn of injectedButtons) {
    const fileId = btn.getAttribute('data-cqd-file-id');
    if (fileId && !modelFileIds.has(fileId)) {
      corrections.push({
        id: `remove-btn:${post.id}:${fileId}`,
        op: 'remove-button',
        priority: 'LOW',
        postId: post.id,
        fileId: fileId,
        element: btn,
        reason: `Orphaned button for file ${fileId} — no longer in model`,
        detectedAt: Date.now(),
        retryCount: 0,
      });
    }
  }

  // CHECK 3: Flag badge vs decision mismatch
  const badge = postEl.querySelector('.cqd-v2-flag');
  const currentVerdict = postEl.getAttribute('data-cqd-v2-flag-verdict');

  if (flagDecision) {
    if (flagDecision.finalVerdict !== 'none') {
      if (!badge) {
        // Decision says flag, but no badge
        corrections.push({
          id: `update-flag:${post.id}`,
          op: 'update-flag',
          priority: basePriority,
          postId: post.id,
          element: postEl,
          reason: `Missing flag badge — decision says ${flagDecision.finalVerdict}`,
          detectedAt: Date.now(),
          retryCount: 0,
        });
      } else if (currentVerdict !== flagDecision.finalVerdict) {
        // Badge shows wrong verdict
        corrections.push({
          id: `update-flag:${post.id}`,
          op: 'update-flag',
          priority: zone === 'visible' ? 'CRITICAL' : basePriority,
          postId: post.id,
          element: postEl,
          reason: `Badge shows "${currentVerdict}" but decision says "${flagDecision.finalVerdict}"`,
          detectedAt: Date.now(),
          retryCount: 0,
        });
      }
    } else {
      // Decision says no flag, but badge exists
      if (badge) {
        corrections.push({
          id: `remove-flag:${post.id}`,
          op: 'remove-flag',
          priority: 'MEDIUM',
          postId: post.id,
          element: postEl,
          reason: `Stale flag badge — decision says "none"`,
          detectedAt: Date.now(),
          retryCount: 0,
        });
      }
    }
  }

  // CHECK 4: Overlay border mismatch
  const overlay = postEl.querySelector('.cqd-v2-overlay');
  if (badge && !overlay) {
    corrections.push({
      id: `fix-overlay:${post.id}`,
      op: 'fix-overlay',
      priority: 'LOW',
      postId: post.id,
      element: postEl,
      reason: 'Badge exists but overlay border is missing',
      detectedAt: Date.now(),
      retryCount: 0,
    });
  }

  // CHECK 5: Duplicate badges (should only have ONE .cqd-v2-flag per post)
  const badges = postEl.querySelectorAll('.cqd-v2-flag');
  if (badges.length > 1) {
    corrections.push({
      id: `dedup-flag:${post.id}`,
      op: 'update-flag',
      priority: 'CRITICAL',
      postId: post.id,
      element: postEl,
      reason: `Duplicate badges found: ${badges.length} badges`,
      detectedAt: Date.now(),
      retryCount: 0,
    });
  }

  // CHECK 6: Duplicate buttons for same file
  const buttonFileIds = new Map<string, number>();
  for (const btn of injectedButtons) {
    const fid = btn.getAttribute('data-cqd-file-id') || '';
    buttonFileIds.set(fid, (buttonFileIds.get(fid) || 0) + 1);
  }
  for (const [fid, count] of buttonFileIds) {
    if (count > 1) {
      corrections.push({
        id: `dedup-btn:${post.id}:${fid}`,
        op: 'remove-button',
        priority: 'HIGH',
        postId: post.id,
        fileId: fid,
        element: postEl,
        reason: `Duplicate buttons for file ${fid}: ${count} found`,
        detectedAt: Date.now(),
        retryCount: 0,
      });
    }
  }

  return corrections;
}

