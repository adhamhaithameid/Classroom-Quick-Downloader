// BATCH VALIDATION
// ============================================================================

/**
 * Validate a batch of posts, respecting the idle deadline.
 *
 * This is the main entry point called from engine-v2.ts via
 * requestIdleCallback. It checks posts one at a time and stops
 * when the idle deadline is about to expire.
 *
 * @param posts - All tracked posts
 * @param flagDecisions - Map of postId → FlagDecision
 * @param placements - All placement decisions
 * @param getViewportZone - Function to get viewport zone for an element
 * @param timeRemaining - Function returning ms left (from IdleDeadline or mock)
 * @param signal - AbortSignal to cancel validation
 * @returns ValidationResult with corrections found
 */
export function validateBatch(
  posts: PostNode[],
  flagDecisions: Map<string, FlagDecision>,
  placements: PlacementDecision[],
  getViewportZone?: (el: HTMLElement) => ViewportZone,
  timeRemaining?: () => number,
  signal?: AbortSignal,
): ValidationResult {
  const startTime = performance.now();
  const allCorrections: CorrectionItem[] = [];
  let postsChecked = 0;
  let unstableSkipped = 0;
  let interrupted = false;

  // Sort posts: visible first, then preload, then offscreen
  const sorted = [...posts].sort((a, b) => {
    const zoneA = getViewportZone?.(a.element) ?? 'offscreen';
    const zoneB = getViewportZone?.(b.element) ?? 'offscreen';
    return zoneOrder(zoneA) - zoneOrder(zoneB);
  });

  for (const post of sorted) {
    // Check abort
    if (signal?.aborted) {
      interrupted = true;
      break;
    }

    // Check deadline
    if (timeRemaining && timeRemaining() < MIN_TIME_REMAINING_MS) {
      interrupted = true;
      break;
    }

    // Check max posts per slice
    if (postsChecked >= MAX_POSTS_PER_SLICE) {
      interrupted = true;
      break;
    }

    // Skip unstable elements
    if (isUnstable(post.id)) {
      unstableSkipped++;
      continue;
    }

    const flagDecision = flagDecisions.get(post.id) || null;
    const postPlacements = placements.filter(p => p.fileId && post.files.some(f => f.canonicalId === p.fileId));

    const corrections = validatePost(post, flagDecision, postPlacements, getViewportZone);
    allCorrections.push(...corrections);
    postsChecked++;
  }

  return {
    postsChecked,
    divergencesFound: allCorrections.length,
    corrections: allCorrections,
    unstableSkipped,
    duration_ms: performance.now() - startTime,
    interrupted,
  };
}

// ============================================================================
// HELPERS
// ============================================================================

/** Convert viewport zone to correction priority */
function zoneToPriority(zone: ViewportZone): CorrectionPriority {
  switch (zone) {
    case 'visible': return 'HIGH';
    case 'preload': return 'MEDIUM';
    case 'offscreen': return 'LOW';
  }
}

/** Sort order for viewport zones (visible=0, preload=1, offscreen=2) */
function zoneOrder(zone: ViewportZone): number {
  switch (zone) {
    case 'visible': return 0;
    case 'preload': return 1;
    case 'offscreen': return 2;
  }
}
