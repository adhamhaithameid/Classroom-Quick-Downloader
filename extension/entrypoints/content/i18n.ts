export type LangKey = keyof typeof TRANSLATIONS.en;

// Cached detected language - set once at startup
let detectedLanguage: string | null = null;
let isInitializing = false;

// Initialize language asynchronously
if (typeof chrome !== 'undefined') {
  (async () => {
    try {
      if (isInitializing) return;
      isInitializing = true;
      const { languageController } = await import('../utils/language-controller');
      const lang = await languageController.getCurrentLanguage();
      if (lang) {
        detectedLanguage = lang;
        console.log('[CQD i18n] Language initialized via controller:', lang);
      }
    } catch (e) {
      console.warn('[CQD i18n] Controller init failed:', e);
    } finally {
      isInitializing = false;
    }
  })();
}

/**
 * Internal function to detect language and set detectedLanguage cache.
 * Returns the detected language code.
 */
function _detectLanguageDirectInternal(): string {
  // If already detected, return it. This prevents re-detection unless explicitly refreshed.
  if (detectedLanguage) {
    return detectedLanguage;
  }

  // Helper to normalize "en-US" -> "en"
  const resolve = (l: string) => {
    const norm = l.toLowerCase().split(';')[0].trim().replace('_', '-');
    const base = norm.split('-')[0];
    return { full: norm, base };
  };

  // candidates to check in order
  const candidates: string[] = [];

  // 1. Get page language
  let pageLang = '';
  if (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang) {
    pageLang = document.documentElement.lang;
  }

  // A) If page lang is set, try it first
  if (pageLang) {
    const p = resolve(pageLang);
    candidates.push(p.full, p.base);
  }

  // 2. Get browser languages
  const browserLangs: string[] = [];
  if (typeof navigator !== 'undefined') {
    if (navigator.language) browserLangs.push(navigator.language);
    if (Array.isArray(navigator.languages)) {
      browserLangs.push(...navigator.languages);
    }
  }

  // B) Then try browser languages
  for (const bl of browserLangs) {
    const b = resolve(bl);
    candidates.push(b.full, b.base);
  }

  // C) Explicit fallback
  candidates.push('en');

  // 3. Find first match
  for (const c of candidates) {
    if (!c) continue;
    if (TRANSLATIONS[c]) {
      detectedLanguage = c;
      console.log('[CQD i18n] Language detected and cached:', c, '| pageLang:', pageLang, '| browserLangs:', browserLangs);
      return c; // Return immediately once found
    }
  }

  // Fallback to English if no match found
  console.warn('[CQD i18n] No matching language found, defaulting to English. Candidates tried:', candidates);
  detectedLanguage = 'en';
  return 'en';
}

/**
 * Direct language detection (fallback when controller unavailable)
 */
export function t(key: LangKey): string {
  try {
    if (!key || typeof key !== 'string') {
      return '...';
    }

    // Ensure language is detected and cached
    // Priority: 1. Controller/Cached value 2. Direct detection
    const lang = detectedLanguage || _detectLanguageDirectInternal();

    // Use the detected language if available
    if (TRANSLATIONS[lang] && typeof TRANSLATIONS[lang][key] === 'string') {
      return TRANSLATIONS[lang][key];
    }

    // Fallback to English if key not found in detected language
    if (TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }

    return key;
  } catch (error) {
    console.warn('CQD i18n lookup failed, falling back to English', error);
    try {
      return TRANSLATIONS['en'][key] || String(key || 'Download');
    } catch {
      return String(key || 'Download');
    }
  }
}

/**
 * Force a language refresh (useful when page language changes or mode switches)
 */
export async function refreshLanguage(): Promise<void> {
  // Clear local cache to force re-evaluation
  detectedLanguage = null;
  
  // Try to refresh via controller if available
  if (typeof chrome !== 'undefined') {
    try {
      const { languageController } = await import('../utils/language-controller');
      await languageController.forceRefresh();
      detectedLanguage = await languageController.getCurrentLanguage();
    } catch (e) {
      console.warn('[CQD i18n] Refresh failed:', e);
      _detectLanguageDirectInternal();
    }
  } else {
    _detectLanguageDirectInternal();
  }
}

/**
 * Get the currently cached language (for debugging)
 */
export function getCurrentCachedLanguage(): string {
  return detectedLanguage || _detectLanguageDirectInternal();
}
